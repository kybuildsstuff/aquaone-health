// Builds the Is it safe? seed migration from supabase/seed/safety_items.json (our own list, in our
// own words: plants from the ASPCA Animal Poison Control lists' facts, plus foods, household products
// and medicines). The output is an idempotent upsert keyed on name; apply it with scripts/migrate.mjs.
//   node scripts/safe-seed-sql.mjs <migration file name>
import { readFile, writeFile } from "node:fs/promises";

const out = process.argv[2];
if (!out) throw new Error("usage: node scripts/safe-seed-sql.mjs supabase/migrations/<timestamp>_safety_items_seed.sql");

const rows = JSON.parse(await readFile("supabase/seed/safety_items.json", "utf8"));
const lit = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (xs) => (xs.length ? `array[${xs.map(lit).join(", ")}]::text[]` : "'{}'::text[]");
const verdict = { safe: "safe", mild: "caution", toxic: "toxic", emergency: "toxic" };

const values = rows.map(
  (r) =>
    `(${lit(r.name)}, ${arr(r.aliases)}, '${r.category}', '${verdict[r.severity]}', '${r.severity}', ${lit(r.summary)}, ${lit(r.what_to_do)}, ${lit(r.source)}, ${lit(r.scientific_name)}, ${lit(r.toxic_principle)})`,
);

const sql = `-- Generated by scripts/safe-seed-sql.mjs from supabase/seed/safety_items.json (${rows.length} items). Do not edit by hand.
insert into safety_items (name, aliases, category, verdict, severity, summary, what_to_do, source, scientific_name, toxic_principle) values
${values.join(",\n")}
on conflict (name) do update set
  aliases = excluded.aliases, category = excluded.category, verdict = excluded.verdict, severity = excluded.severity,
  summary = excluded.summary, what_to_do = excluded.what_to_do, source = excluded.source,
  scientific_name = excluded.scientific_name, toxic_principle = excluded.toxic_principle, updated_at = now();
`;
await writeFile(out, sql);
console.log(`wrote ${out}: ${rows.length} items`);
